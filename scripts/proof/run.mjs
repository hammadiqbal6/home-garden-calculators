#!/usr/bin/env node
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { writeAdsenseReadiness } from './lib/adsense-md.mjs';
import { writeBundleSizeReport } from './lib/bundle-size.mjs';
import { writeLighthouseProof } from './lib/lighthouse-proof.mjs';
import { writeMobileProof } from './lib/mobile-capture.mjs';
import { writeSitemapRobotsReport } from './lib/sitemap-robots.mjs';
import { writeStructuredDataProof } from './lib/structured-data.mjs';
import { startStaticServer } from './lib/static-server.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '../..');
const PROOF = path.join(ROOT, 'docs/proof');

function readPkgVersion(name) {
  try {
    const p = JSON.parse(
      fs.readFileSync(path.join(ROOT, 'node_modules', name, 'package.json'), 'utf8'),
    );
    return p.version;
  } catch {
    return 'unknown';
  }
}

function runCapture(cmd, args, outFile) {
  const r = spawnSync(cmd, args, { cwd: ROOT, encoding: 'utf8', shell: process.platform === 'win32' });
  const text = [r.stdout, r.stderr].filter(Boolean).join('\n');
  fs.writeFileSync(outFile, text);
  return r.status ?? 1;
}

function ensureDist() {
  if (!fs.existsSync(path.join(ROOT, 'dist'))) {
    console.error('dist/ missing — run npm run build first');
    process.exit(1);
  }
}

async function writeReadme(meta) {
  const lines = [
    '# Proof bundle',
    '',
    'Committed SEO, performance, AdSense, and test evidence generated by **`npm run proof`** (never hand-edited scores).',
    '',
    `Last generated: **${meta.generatedUtc}** (UTC)`,
    '',
    '## Index',
    '',
    '| Check | Tool | Version | Budget | Result | Reproduce |',
    '| --- | --- | --- | --- | --- | --- |',
    `| Unit tests | vitest | ${meta.versions.vitest} | 21 tests pass | ${meta.testsPass ? 'PASS' : 'FAIL'} | \`npm test\` → [tests.txt](./tests.txt) |`,
    `| SEO / perf / AdSense audits | node auditors | repo scripts | 0 errors | ${meta.auditPass ? 'PASS' : 'FAIL'} | \`npm run audit\` → [seo-audit.txt](./seo-audit.txt) |`,
    `| JS bundle (first-party) | node perf auditor | — | ≤50KB gzip/page | ${meta.bundlePass ? 'PASS' : 'FAIL'} | see [bundle-size.txt](./bundle-size.txt) |`,
    `| Sitemap & robots | node proof script | — | valid XML, bots, llms.txt | ${meta.sitemapPass ? 'PASS' : 'FAIL'} | [sitemap-robots.txt](./sitemap-robots.txt) |`,
    `| Structured data | node proof script | — | required @types per page type | ${meta.structuredPass ? 'PASS' : 'FAIL'} | [structured-data/](./structured-data/) |`,
    `| Lighthouse mobile + desktop | lighthouse | ${meta.versions.lighthouse} | ≥95 cats; LCP≤2.5s; CLS≤0.05 | ${meta.lighthousePass ? 'PASS' : 'FAIL'} | [lighthouse/summary.md](./lighthouse/summary.md) |`,
    `| Mobile screenshots | playwright | ${meta.versions.playwright} | 360 & 768px, no horizontal scroll | ${meta.mobilePass ? 'PASS' : 'FAIL'} | [mobile/](./mobile/) |`,
    `| AdSense readiness | node proof script | — | trust pages, ads.txt, depth | ${meta.adsensePass ? 'PASS' : 'FAIL'} | [adsense-readiness.md](./adsense-readiness.md) |`,
    '',
    '## Full regenerate',
    '',
    '```bash',
    'npm run build',
    'npm run proof',
    '```',
    '',
    'After deploy, re-run [Google Rich Results Test](https://search.google.com/test/rich-results) on live URLs (see structured-data note).',
    '',
  ];
  fs.writeFileSync(path.join(PROOF, 'README.md'), lines.join('\n') + '\n');
}

async function main() {
  process.chdir(ROOT);
  ensureDist();

  const generatedUtc = new Date().toISOString().replace(/\.\d{3}Z$/, 'Z');
  fs.mkdirSync(PROOF, { recursive: true });
  fs.mkdirSync(path.join(PROOF, 'lighthouse'), { recursive: true });
  fs.mkdirSync(path.join(PROOF, 'structured-data'), { recursive: true });
  fs.mkdirSync(path.join(PROOF, 'mobile'), { recursive: true });

  const testsCode = runCapture('npm', ['test'], path.join(PROOF, 'tests.txt'));
  const testsPass = testsCode === 0;

  const auditCode = runCapture('npm', ['run', 'audit'], path.join(PROOF, 'seo-audit.txt'));
  const auditPass = auditCode === 0;

  const bundle = writeBundleSizeReport(path.join(PROOF, 'bundle-size.txt'));
  const bundlePass = bundle.errors === 0;

  const sitemap = writeSitemapRobotsReport(path.join(PROOF, 'sitemap-robots.txt'));
  const sitemapPass = sitemap.pass;

  const structured = writeStructuredDataProof(path.join(PROOF, 'structured-data'));
  const structuredPass = structured.errors === 0;

  const adsenseThin = writeAdsenseReadiness(path.join(PROOF, 'adsense-readiness.md'), generatedUtc);
  const adsensePass = adsenseThin.thinCount === 0 && auditPass;

  const { server, baseUrl, close } = await startStaticServer(path.join(ROOT, 'dist'));

  let lighthousePass = true;
  let mobilePass = true;
  try {
    const lh = await writeLighthouseProof(path.join(PROOF, 'lighthouse'), baseUrl);
    lighthousePass = lh.failures === 0;

    const mobile = await writeMobileProof(path.join(PROOF, 'mobile'), baseUrl);
    mobilePass = mobile.scrollFails === 0;
  } finally {
    await close();
  }

  const versions = {
    vitest: readPkgVersion('vitest'),
    lighthouse: readPkgVersion('lighthouse'),
    playwright: readPkgVersion('playwright'),
  };

  await writeReadme({
    generatedUtc,
    versions,
    testsPass,
    auditPass,
    bundlePass,
    sitemapPass,
    structuredPass,
    lighthousePass,
    mobilePass,
    adsensePass,
  });

  const results = {
    tests: testsPass,
    audit: auditPass,
    bundle: bundlePass,
    sitemap: sitemapPass,
    structured: structuredPass,
    lighthouse: lighthousePass,
    mobile: mobilePass,
    adsense: adsensePass,
  };
  const failed = Object.entries(results)
    .filter(([, ok]) => !ok)
    .map(([name]) => name);

  if (failed.length) {
    console.error(
      `Proof generation completed with failures (${failed.join(', ')}) — fix budgets and re-run npm run proof`,
    );
    if (!lighthousePass) {
      try {
        const summary = fs.readFileSync(path.join(PROOF, 'lighthouse', 'summary.md'), 'utf8');
        const failSection = summary.split('## Failures')[1];
        if (failSection) console.error(failSection.trim());
      } catch {
        /* summary may be missing */
      }
    }
    process.exit(1);
  }
  console.log(`Proof bundle written to ${PROOF}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
